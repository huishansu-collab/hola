import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const source=fs.readFileSync('components/case-directory.ts','utf8').replaceAll('export ','');
const code=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText;
const moveCase=Function(code+';return moveCase')();
const a={id:'a',name:'A'},b={id:'b',name:'B'},c={id:'c',name:'C'};
const initial=[{id:'one',name:'One',cases:[a,b,c]},{id:'empty',name:'Empty',cases:[]}];
const ids=x=>x.map(f=>f.cases.map(c=>c.id));
assert.deepEqual(ids(moveCase(initial,'a',{folderId:'one',caseId:'c',edge:'after'})),[['b','c','a'],[]]);
assert.deepEqual(ids(moveCase(initial,'c',{folderId:'one',caseId:'a',edge:'before'})),[['c','a','b'],[]]);
const moved=moveCase(initial,'b',{folderId:'empty'});
assert.deepEqual(ids(moved),[['a','c'],['b']]);
assert.equal(moved[1].cases[0],b);
assert.deepEqual(ids(JSON.parse(JSON.stringify(moved))),[['a','c'],['b']]);
assert.deepEqual(ids(moveCase(moved,'b',{folderId:'one',caseId:'c',edge:'before'})),[['a','b','c'],[]]);
assert.equal(moveCase(initial,'a',{folderId:'missing'}),initial);
assert.equal(moveCase(initial,'a',{folderId:'one',caseId:'a'}),initial);
assert.deepEqual(ids(initial),[['a','b','c'],[]]);
console.log('PASS: reordering, cross-folder moves, empty folders, persistence data, no duplicates, unchanged IDs and source.');
